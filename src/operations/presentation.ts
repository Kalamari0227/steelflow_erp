export function locationLabel(id: string, world: World): string {
  const name = world.locations.find(row => row.id === id)?.name;
  if (name && name !== id && !name.startsWith('OPS-')) return name;
  if (id === 'OPS-HSM-A-HSM-B-ROLLER') return '열연 예비 설비 연결 롤러';
  const roller = /^OPS-ROLLER-(.+)--(.+)$/.exec(id);
  if (roller?.[1] && roller[2]) return `${equipmentLabel(roller[1])} → ${equipmentLabel(roller[2])} · 이송 롤러`;
  const match = /^OPS-(.+)-(ENTRY|WORK|EXIT|BUFFER|HOOK|CARGO)$/.exec(id);
  if (!match?.[1] || !match[2]) return name ?? id;
  const owner = match[1].replace(/^CRANE-/, '');
  const suffix: Readonly<Record<string, string>> = { ENTRY: '투입부', WORK: '가공부', EXIT: '배출부', BUFFER: '대기장', HOOK: '크레인 인양부', CARGO: '적재함' };
  return equipmentNames[owner] ? `${equipmentNames[owner]} · ${suffix[match[2]]}` : name ?? id;
}

